//! Environment definitions, persisted as JSON in the OS app-config directory
//! (macOS: ~/Library/Application Support/com.aemenv.manager/environments.json).

use serde::{Deserialize, Serialize};
use std::path::PathBuf;
use tauri::{AppHandle, Manager};

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
#[serde(rename_all = "lowercase")]
pub enum Kind {
    Author,
    Publish,
}

impl Kind {
    pub fn runmode(&self) -> &'static str {
        match self {
            Kind::Author => "author",
            Kind::Publish => "publish",
        }
    }
}

/// Id of the workspace that existing (pre-workspace) environments belong to.
pub const DEFAULT_WORKSPACE: &str = "default";

fn default_workspace() -> String {
    DEFAULT_WORKSPACE.to_string()
}

/// A named group of environments (e.g. one per client/project).
#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct Workspace {
    pub id: String,
    pub name: String,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(rename_all = "camelCase")]
pub struct Environment {
    /// Stable unique id (generated by the UI).
    pub id: String,
    /// Workspace this environment belongs to. Missing in old configs => "default".
    #[serde(default = "default_workspace")]
    pub workspace_id: String,
    pub name: String,
    pub kind: Kind,
    /// Folder that contains `crx-quickstart` (or the quickstart jar for a first start).
    pub dir: String,
    pub port: u16,
    /// AEM quickstart jar used to start the instance: a file name inside `dir`.
    /// When saving, an absolute path outside `dir` is copied into `dir` and replaced by its file name.
    #[serde(default)]
    pub jar: String,
    /// Extra runmodes, comma separated (e.g. "local,dev"). `author`/`publish` is added automatically.
    #[serde(default)]
    pub extra_runmodes: String,
    /// Extra JVM options, e.g. "-Xmx2g -agentlib:jdwp=transport=dt_socket,server=y,suspend=n,address=*:5005".
    #[serde(default)]
    pub jvm_opts: String,
    /// Optional full override of the start command (run through the shell, cwd = `dir`).
    #[serde(default)]
    pub start_command: String,
    /// Optional full override of the stop command (run through the shell, cwd = `dir`).
    #[serde(default)]
    pub stop_command: String,
}

fn file(app: &AppHandle) -> Result<PathBuf, String> {
    let dir = app.path().app_config_dir().map_err(|e| e.to_string())?;
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    Ok(dir.join("environments.json"))
}

pub fn load(app: &AppHandle) -> Result<Vec<Environment>, String> {
    let path = file(app)?;
    if !path.exists() {
        return Ok(vec![]);
    }
    let text = std::fs::read_to_string(&path).map_err(|e| e.to_string())?;
    serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))
}

pub fn store(app: &AppHandle, envs: &[Environment]) -> Result<(), String> {
    let text = serde_json::to_string_pretty(envs).map_err(|e| e.to_string())?;
    std::fs::write(file(app)?, text).map_err(|e| e.to_string())
}

pub fn find(app: &AppHandle, id: &str) -> Result<Environment, String> {
    load(app)?
        .into_iter()
        .find(|e| e.id == id)
        .ok_or_else(|| format!("Unknown environment: {id}"))
}

fn workspaces_file(app: &AppHandle) -> Result<PathBuf, String> {
    Ok(file(app)?.with_file_name("workspaces.json"))
}

/// Always returns at least one workspace (a "Default" one is created on first use).
pub fn load_workspaces(app: &AppHandle) -> Result<Vec<Workspace>, String> {
    let path = workspaces_file(app)?;
    if path.exists() {
        let text = std::fs::read_to_string(&path).map_err(|e| e.to_string())?;
        let list: Vec<Workspace> = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        if !list.is_empty() {
            return Ok(list);
        }
    }
    let list = vec![Workspace { id: DEFAULT_WORKSPACE.into(), name: "Default".into() }];
    store_workspaces(app, &list)?;
    Ok(list)
}

pub fn store_workspaces(app: &AppHandle, list: &[Workspace]) -> Result<(), String> {
    let text = serde_json::to_string_pretty(list).map_err(|e| e.to_string())?;
    std::fs::write(workspaces_file(app)?, text).map_err(|e| e.to_string())
}
